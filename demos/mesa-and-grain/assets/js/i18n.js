(function () {
  "use strict";
  var STR = window.MESA_STRINGS;
  var KEY = "mesa-and-grain-lang";
  var supported = { en: 1, es: 1, fr: 1 };

  function current() {
    var q = new URLSearchParams(window.location.search).get("lang");
    if (q && supported[q]) return q;
    var h = (window.location.hash || "").replace("#", "");
    if (supported[h]) return h;
    try { var s = localStorage.getItem(KEY); if (s && supported[s]) return s; } catch (e) {}
    var n = (navigator.language || "en").slice(0, 2);
    return supported[n] ? n : "en";
  }

  function apply(lang) {
    if (!supported[lang]) lang = "en";
    var pack = STR[lang] || STR.en;
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (pack[k] != null) el.textContent = pack[k];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-placeholder");
      if (pack[k] != null) el.setAttribute("placeholder", pack[k]);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-aria");
      if (pack[k] != null) el.setAttribute("aria-label", pack[k]);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-alt");
      if (pack[k] != null) el.setAttribute("alt", pack[k]);
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-title");
      if (pack[k] != null) el.setAttribute("title", pack[k]);
    });
    var title = document.querySelector("title");
    if (title && pack["meta.title"]) title.textContent = pack["meta.title"];
    var meta = document.querySelector('meta[name="description"]');
    if (meta && pack["meta.description"]) meta.setAttribute("content", pack["meta.description"]);
    document.querySelectorAll("[data-set-lang]").forEach(function (btn) {
      btn.setAttribute("aria-pressed", String(btn.getAttribute("data-set-lang") === lang));
    });
    try { localStorage.setItem(KEY, lang); } catch (e) {}
  }

  window.mesaSetLang = apply;
  document.addEventListener("click", function (e) {
    var btn = e.target.closest("[data-set-lang]");
    if (!btn) return;
    e.preventDefault();
    apply(btn.getAttribute("data-set-lang"));
  });
  apply(current());
})();
